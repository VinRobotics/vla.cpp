"""Port the C++ that `ggml-compiler compile --emit cpp --name cosmos3` generated into
src/models/cosmos3_edge_graphs.cpp, the one vla.cpp source file that is not hand written.

    python scripts/port_cosmos3_graphs.py --in out/cosmos3/cpp/cosmos3.cpp \\
        --out src/models/cosmos3_edge_graphs.cpp

Only the frame changes: the include of the generated header becomes cosmos3_edge_build.h, the ops header
becomes cosmos3_edge_ops.h, the anonymous namespace becomes vla::cosmos3_edge_graphs (so the builders can be
declared in the header), and the registration table plus `cosmos3_load` at the end (they bind the generated
code to ggml-compiler's runtime) are dropped. Every ggml call in the five builders is kept as generated.
"""

