"""Cosmos3-Edge-Policy (lerobot/Cosmos3-Edge-Policy-LIBERO) -> vla.cpp GGUF.

Unlike the other converters this one does not read the safetensors checkpoint. The graphs of
src/models/cosmos3_edge_graphs.cpp were generated by ggml-compiler from a PyTorch re-statement of the
model's inference (ggml/export.py in the port's repo), and they look their weights up by the compiler's
own names (`w.<i>` for parameters, `c.<i>` for constants it folded at compile time: the VAE's 2-D
kernels, the DomainAwareLinear slice of domain 5, mask and RoPE tables). The weights are therefore taken
from the same `ggml-compiler compile` run, so graphs and weights cannot disagree:

    ggml-compiler compile ggml/export.py:program --out out/cosmos3 --emit gguf,cpp --name cosmos3 \\
        --policy ggml/policy-bf16.yaml
    python scripts/convert_cosmos3_edge_to_gguf.py --ckpt out/cosmos3/model.gguf --out cosmos3-edge-bf16.gguf

Tensors are copied byte for byte (BF16 weights stay BF16, the VAE kernels F16, norms and constants F32).
The converter adds the architecture key, the sizes the runtime needs, and `cosmos3_edge.step_scalars`
[n_steps, n_scalars], the per-step UniPC coefficients that the compiler's driver feeds to the denoising stage.

With `--policy-dir` (the checkpoint's directory: `config.json` and `tokenizer/`) it also embeds the model's
byte-level BPE tokenizer (llama.cpp's `tokenizer.ggml.*` keys) and the caption settings, so `vla-cli --text`
can build the prompt of a task itself (src/models/cosmos3_edge_prompt.cpp).
"""

from __future__ import annotations

import json
import math
import sys
from pathlib import Path

import numpy as np

import gguf
from gguf_common import (
    F32,
    arg_parser,
    copy_tensor,
    finish,
    kv_prefix,
    kv_u32,
    open_writer,
    resolve_out,
)

ARCH = "cosmos3_edge"
KV = kv_prefix(ARCH)

# Stage parameters of the compiled driver, in the order the generated builders read them.
STAGES = ("vae_encode", "prefix", "init", "step", "finish")
INPUTS = ("canvas", "input_ids", "attention_mask", "video_noise", "action_noise")
OUTPUTS = ("actions", "xv")
SCALARS = ("t", "sigma", "E", "A", "B", "C", "D", "Fc", "Gc", "Hc")


def program_of(reader: gguf.GGUFReader) -> dict:
    f = reader.fields.get("ggml_compiler.program")
    if f is None:
        raise SystemExit("not a ggml-compiler GGUF: no ggml_compiler.program key")
    return json.loads(bytes(f.parts[-1]).decode())


def string_of(reader: gguf.GGUFReader, key: str) -> str:
    f = reader.fields.get(key)
    return bytes(f.parts[-1]).decode() if f is not None else ""


def parse_program(prog: dict) -> dict:
    """Check that `prog` (the compiler's ggml_compiler.program) is the program the graphs of
    src/models/cosmos3_edge_graphs.cpp were generated from, and read the sizes and the per-step scalars out of
    it. Pure Python: the scalar table is returned as rows of floats, one per denoising step."""
    stages = [s["name"] for s in prog["stages"]]
    if tuple(stages) != STAGES:
        raise SystemExit(f"expected stages {STAGES}, the program has {tuple(stages)}")
    values = {v["name"]: v for v in prog["values"]}
    ins = [v["name"] for v in prog["inputs"]] if prog["inputs"] and isinstance(prog["inputs"][0], dict) else list(prog["inputs"])
    if tuple(ins) != INPUTS:
        raise SystemExit(f"expected inputs {INPUTS}, the program has {tuple(ins)}")

    loops = [op for op in prog["driver"] if op["op"] == "loop"]
    if len(loops) != 1:
        raise SystemExit(f"expected one denoising loop, found {len(loops)}")
    loop = loops[0]
    names = tuple(s["value"] for s in loop["scalars"])
    if names != SCALARS:
        raise SystemExit(f"expected loop scalars {SCALARS}, the program has {names}")
    n_steps = int(loop["n"])
    cols = [[float(x) for x in s["values"]] for s in loop["scalars"]]
    if any(len(c) != n_steps for c in cols):
        raise SystemExit(f"the scalar tables do not all have {n_steps} steps")
    table = [[c[k] for c in cols] for k in range(n_steps)]  # [n_steps][len(SCALARS)]

    def ne(name: str) -> list[int]:
        return [int(x) for x in values[name]["ne"]]  # ggml order, innermost first

    canvas_w, canvas_h, _, _ = ne("canvas")
    return {
        "table": table, "n_steps": n_steps,
        "canvas_h": canvas_h, "canvas_w": canvas_w, "prompt_len": ne("input_ids")[0],
        "video_tok": ne("video_noise")[1], "video_dim": ne("video_noise")[0],
        "horizon": ne("action_noise")[1], "action_dim": ne("action_noise")[0],
    }


def caption_settings(config: dict, canvas_h: int, canvas_w: int) -> dict:
    """The settings of lerobot's Cosmos3PromptProcessorStep, from the policy's config.json."""
    # The aspect ratio the processor puts in the caption: the name of the tier canvas of that size (the 192x320
    # canvas of this model is the 16:9 one), else the reduced width and height.
    known = {(320, 192): "16,9"}
    ratio = known.get((canvas_w, canvas_h))
    if ratio is None:
        d = math.gcd(canvas_w, canvas_h)
        ratio = f"{canvas_w // d},{canvas_h // d}"
    return {
        "view_description": str(config["view_description"]),
        "aspect_ratio": ratio,
        "fps": float(config["fps"]),
        "use_state": 1 if config.get("use_state") else 0,
        "chunk_size": int(config["chunk_size"]),
    }


def add_tokenizer(writer, tok_dir: Path) -> None:
    """The BPE of tokenizer.json as llama.cpp's GGUF vocabulary keys (gpt2 model, "tekken" pre-tokenizer)."""
    d = json.loads((tok_dir / "tokenizer.json").read_text())
    cfg = json.loads((tok_dir / "tokenizer_config.json").read_text())
    m = d["model"]
    if m["type"] != "BPE" or not m.get("ignore_merges") or m.get("byte_fallback"):
        raise SystemExit("expected a byte-level BPE tokenizer with ignore_merges, as the Cosmos3 tokenizer is")
    vocab = m["vocab"]
    tokens = [None] * len(vocab)
    for tok, i in vocab.items():
        tokens[i] = tok
    if any(t is None for t in tokens):
        raise SystemExit("the vocabulary has gaps")
    types = [1] * len(tokens)  # llama.cpp: 1 normal, 2 unknown, 3 control, 4 user defined
    for a in d["added_tokens"]:
        types[a["id"]] = 3 if a["special"] else 4
    types[vocab[cfg["unk_token"]]] = 2
    merges = [" ".join(x) if isinstance(x, list) else x for x in m["merges"]]
    writer.add_string("tokenizer.ggml.model", "gpt2")
    writer.add_string("tokenizer.ggml.pre", "tekken")
    writer.add_array("tokenizer.ggml.tokens", tokens)
    writer.add_array("tokenizer.ggml.token_type", types)
    writer.add_array("tokenizer.ggml.merges", merges)
    for key, name in (("bos_token_id", "bos_token"), ("eos_token_id", "eos_token"), ("unknown_token_id", "unk_token"),
                      ("padding_token_id", "pad_token")):
        writer.add_uint32(f"tokenizer.ggml.{key}", vocab[cfg[name]])
    writer.add_bool("tokenizer.ggml.add_bos_token", False)
    print(f"tokenizer: {len(tokens)} tokens, {len(merges)} merges, {sum(t in (3, 4) for t in types)} special")


def main() -> int:
    ap = arg_parser(
        ARCH,
        "model.gguf written by `ggml-compiler compile` of ggml/export.py (bf16 policy recommended)",
        description=__doc__,
    )
    ap.add_argument("--policy-dir", type=Path, default=None,
                    help="the checkpoint's directory (config.json, tokenizer/): embeds the tokenizer and the caption settings")
    args = ap.parse_args()
    src = args.ckpt.resolve()
    if src.is_dir():
        src = src / "model.gguf"
    if not src.exists():
        raise SystemExit(f"missing {src}")
    out = args.out.resolve() if args.out else resolve_out(args, src.parent, ARCH)

    reader = gguf.GGUFReader(str(src))
    prog = program_of(reader)

    info = parse_program(prog)
    table, n_steps = info["table"], info["n_steps"]
    canvas_h, canvas_w, prompt_len = info["canvas_h"], info["canvas_w"], info["prompt_len"]
    video_tok, video_dim, horizon, action_dim = info["video_tok"], info["video_dim"], info["horizon"], info["action_dim"]

    writer = open_writer(out, ARCH)
    kv_u32(writer, KV, {
        "canvas_h": canvas_h, "canvas_w": canvas_w, "prompt_len": prompt_len,
        "video_noise_tokens": video_tok, "video_noise_dim": video_dim,
        "num_steps": n_steps, "chunk_size": horizon, "action_dim": action_dim,
        "max_action_dim": 64, "n_scalars": len(SCALARS), "n_layers": 28,
        "n_tensors_expected": len(reader.tensors),
    })
    writer.add_string(KV("scalars"), json.dumps(list(SCALARS)))
    writer.add_string(KV("tensor_names"), string_of(reader, "ggml_compiler.tensor_names"))
    writer.add_string(KV("source"), json.dumps({
        "compiler_gguf": src.name, "compiler_source": string_of(reader, "ggml_compiler.source"),
        "options": string_of(reader, "ggml_compiler.options"),
        "specialized": prog.get("specialized", None),
    }))
    writer.add_string(KV("io_meta"), string_of(reader, "ggml_compiler.meta"))

    if args.policy_dir is not None:
        pdir = args.policy_dir.resolve()
        cs = caption_settings(json.loads((pdir / "config.json").read_text()), canvas_h, canvas_w)
        if cs["chunk_size"] != horizon:
            raise SystemExit(f"config.json chunk_size {cs['chunk_size']} is not the program's {horizon}")
        writer.add_string(KV("caption.view_description"), cs["view_description"])
        writer.add_string(KV("caption.aspect_ratio"), cs["aspect_ratio"])
        writer.add_float32(KV("caption.fps"), cs["fps"])
        writer.add_uint32(KV("caption.use_state"), cs["use_state"])
        add_tokenizer(writer, pdir / "tokenizer")

    n = 0
    for t in reader.tensors:
        copy_tensor(writer, t)
        n += 1
    writer.add_tensor(KV("step_scalars"), np.ascontiguousarray(np.asarray(table, dtype=np.float32)), raw_dtype=F32)
    print(f"{n} tensors copied, {n_steps} steps x {len(SCALARS)} scalars, canvas {canvas_h}x{canvas_w}, "
          f"prompt {prompt_len}, video noise {video_tok}x{video_dim}, actions {horizon}x{action_dim}")
    return finish(writer, out)


if __name__ == "__main__":
    sys.exit(main())
