// What the ggml graph builders of cosmos3_edge_graphs.cpp need from their host.
//
// Those builders were generated by ggml-compiler (`ggml-compiler compile --emit cpp`). They reach their
// host through five calls: the graph context, whether the backend is a GPU, the stage's parameters, a
// weight by GGUF name, and the stage's outputs. ggml-compiler's runtime provides them; this header
// provides them for vla.cpp, so the generated code is used as it is (see scripts/port_cosmos3_graphs.py).

#pragma once

#include "ggml.h"

#include <string>
#include <unordered_map>
#include <vector>

namespace vla::cosmos3_edge_graphs {

// What one stage builder is given and returns. The arch fills `params` (in the order of the stage's
// parameters in the compiled driver), reads `outputs` back after the call, and checks `error`.
struct ggml_compiler_stage_build {
    ggml_context *                                      ctx = nullptr;
    bool                                                gpu = false;
    std::vector<ggml_tensor *>                          params;
    std::vector<ggml_tensor *>                          outputs;
    const std::unordered_map<std::string, ggml_tensor *> * weights = nullptr;
    std::string                                         error;  // first problem, empty when none
};

inline ggml_context * ggml_compiler_build_ctx(ggml_compiler_stage_build * b) {
    return b->ctx;
}

inline bool ggml_compiler_build_gpu(ggml_compiler_stage_build * b) {
    return b->gpu;
}

// A missing parameter or weight is recorded and answered with a 1-element tensor so the builder can run to
// the end; the arch refuses the stage afterwards.
inline ggml_tensor * ggml_compiler_build_param(ggml_compiler_stage_build * b, int i) {
    if (i >= 0 && (size_t) i < b->params.size() && b->params[(size_t) i])
        return b->params[(size_t) i];
    if (b->error.empty())
        b->error = "missing stage parameter " + std::to_string(i);
    return ggml_new_tensor_1d(b->ctx, GGML_TYPE_F32, 1);
}

inline ggml_tensor * ggml_compiler_build_weight(ggml_compiler_stage_build * b, const char * name) {
    const auto it = b->weights->find(name);
    if (it != b->weights->end())
        return it->second;
    if (b->error.empty())
        b->error = std::string("missing weight ") + name;
    return ggml_new_tensor_1d(b->ctx, GGML_TYPE_F32, 1);
}

inline void ggml_compiler_build_output(ggml_compiler_stage_build * b, int i, ggml_tensor * t) {
    if (i < 0)
        return;
    if ((size_t) i >= b->outputs.size())
        b->outputs.resize((size_t) i + 1, nullptr);
    b->outputs[(size_t) i] = t;
}

// The five stage builders, in the order of the compiled driver. 0 on success.
int build_vae_encode(ggml_compiler_stage_build * B);
int build_prefix(ggml_compiler_stage_build * B);
int build_init(ggml_compiler_stage_build * B);
int build_step(ggml_compiler_stage_build * B);
int build_finish(ggml_compiler_stage_build * B);

}  // namespace vla::cosmos3_edge_graphs
