// Cosmos3-Edge-Policy (LIBERO): a world-action model. One 28-layer Mixture-of-Transformers backbone denoises
// 4 latent video frames and a 16-step action chunk together, conditioned on the VAE latent of the current
// frame and on the prompt, with 30 UniPC steps.
//
// The graphs are not written here: src/models/cosmos3_edge_graphs.cpp was generated by ggml-compiler (see
// scripts/port_cosmos3_graphs.py) for five stages, and this file is the engine around them:
//   vae_encode(canvas)               -> z0                   Wan2.2 encoder, one frame
//   prefix(input_ids, mask)          -> K/V of 28 layers, bias, cos, sin   the understanding stream, once
//   init(z0, video_noise, action_noise) -> the 8 values the denoising loop carries
//   step(carries, K/V, ..., 10 scalars) x 30                     one UniPC update, the scalars per step
//   finish(xa)                       -> actions              de-normalized (q01/q99), rot6d
// Values that cross stages stay in one device buffer; a graph writes its outputs into it with ggml_cpy. The
// step graph ends by copying its outputs back into the carries it read, so a denoising step is one graph
// compute and one upload of its 10 scalars, with no other host round trip.
//
// The input contract is the one of the compiled program (see docs/MODELS.md): two camera views, in the
// order [third person, wrist], composed into the 192x320 canvas here exactly as lerobot's
// Cosmos3VideoCanvasProcessorStep does (or one canvas the caller composed); the prompt as token ids, which
// src/models/cosmos3_edge_prompt.cpp builds from the instruction (vla-cli --text); `Inputs::noise` the 16x10
// action noise (video noise is drawn here, or read from VLA_COSMOS3_VIDEO_NOISE). The 10 action columns are
// [dpos(3), rot6d(6), gripper]; cosmos3_libero_action (same file) decodes them to a LIBERO command.

