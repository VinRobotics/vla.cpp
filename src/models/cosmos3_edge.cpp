constexpr int kViews        = 2;    // [third person, wrist]
constexpr int kViewSize     = 256;  // each view, square (lerobot view_size)
constexpr int kContentH     = 160;  // the composed 256x512 frame fit into the canvas, never enlarged
constexpr int kContentW     = 320;
constexpr int kCarries      = 8;    // xv xa lv la m1v m1a m2v m2a
constexpr int kLayers       = 28;
constexpr int kPrefixOuts   = kLayers * 2 + 3;  // K and V per layer, bias, cos, sin
constexpr int kScalars      = 10;   // t sigma E A B C D Fc Gc Hc
constexpr int kStageCount   = 5;
constexpr int kGraphNodes   = 16384;  // the cap of one stage graph; the largest (step) has about 2,200 nodes

enum StageId { VAE = 0, PREFIX = 1, INIT = 2, STEP = 3, FINISH = 4 };

double now_ms() {
    using clock = std::chrono::steady_clock;
    return std::chrono::duration<double, std::milli>(clock::now().time_since_epoch()).count();
}

